const MIME_FROM_MAGIC: Array<{ mime: string; sig: Uint8Array; mask?: Uint8Array }> = [];
for (const [mime, sigs] of Object.entries(MAGIC_BYTES)) {
  for (const sig of sigs) {
    MIME_FROM_MAGIC.push({ mime, sig });
  }
}

export function validateMimeByMagic(buffer: Uint8Array, declaredMime: string): boolean {
  if (declaredMime === 'text/plain') return true;

  for (const { mime, sig } of MIME_FROM_MAGIC) {
    if (mime !== declaredMime) continue;
    if (buffer.length < sig.length) continue;
    let match = true;
    for (let i = 0; i < sig.length; i++) {
      if (buffer[i] !== sig[i]) { match = false; break; }
    }
    if (match) return true;
  }

  return false;
}
